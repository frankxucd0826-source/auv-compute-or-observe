"""Assemble the revision-8 request (polish the whole paper along one main line, standard terms, shorter):
the brief, the new term list, the fact lists, both tables and all current section files.
    python -E -X utf8 paper/gemini/build_prompt_rev8.py   -> paper/gemini/prompt_rev8.txt
"""
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
FILES = ["title", "abstract", "intro", "related", "prior", "problem", "method", "experiments", "innovation",
         "conclusion", "appendix"]


def main():
    parts = [("brief_rev8.md", (PAPER / "gemini/brief_rev8.md").read_text(encoding="utf-8")),
             ("terms_v6.md", (PAPER / "gemini/terms_v6.md").read_text(encoding="utf-8")),
             ("facts_v4.md", (PAPER / "gemini/facts_v4.md").read_text(encoding="utf-8")),
             ("facts_v3.md", (PAPER / "gemini/facts_v3.md").read_text(encoding="utf-8")),
             ("tables/route_settings.tex (Table 1, to be rewritten in the new terms)", (PAPER / "tables/route_settings.tex").read_text(encoding="utf-8")),
             ("tables/route_scope.tex (Table 2, generated by a script; Claude renames its headers to the new terms)",
              (PAPER / "tables/route_scope.tex").read_text(encoding="utf-8"))]
    for f in FILES:
        parts.append((f"sections/{f}.tex (current text, to be rewritten)", (PAPER / f"sections/{f}.tex").read_text(encoding="utf-8")))
    text = "".join(f"\n\n########## ATTACHED FILE: {name} ##########\n\n{body}" for name, body in parts)
    out = PAPER / "gemini/prompt_rev8.txt"
    out.write_text(text, encoding="utf-8")
    print(out, len(text), "chars")


if __name__ == "__main__":
    main()
