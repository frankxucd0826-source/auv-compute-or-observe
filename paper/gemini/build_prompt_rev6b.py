"""Assemble the revision-6b request (the third region): the brief, the new and the
earlier fact lists, the terms and the current section files.
    python -E -X utf8 paper/gemini/build_prompt_rev6b.py   -> paper/gemini/prompt_rev6b.txt
"""
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
FILES = ["abstract", "intro", "method", "experiments", "innovation", "conclusion"]


def main():
    parts = [("brief_rev6b.md", (PAPER / "gemini/brief_rev6b.md").read_text(encoding="utf-8")),
             ("facts_v4.md", (PAPER / "gemini/facts_v4.md").read_text(encoding="utf-8")),
             ("facts_v3.md", (PAPER / "gemini/facts_v3.md").read_text(encoding="utf-8")),
             ("terms_v5.md", (PAPER / "gemini/terms_v5.md").read_text(encoding="utf-8")),
             ("tables/route_scope.tex (generated by the script; includes the Gulf Stream and Agulhas rows)",
              (PAPER / "tables/route_scope.tex").read_text(encoding="utf-8"))]
    for f in FILES:
        parts.append((f"sections/{f}.tex (current, checked text)", (PAPER / f"sections/{f}.tex").read_text(encoding="utf-8")))
    text = "".join(f"\n\n########## ATTACHED FILE: {name} ##########\n\n{body}" for name, body in parts)
    out = PAPER / "gemini/prompt_rev6b.txt"
    out.write_text(text, encoding="utf-8")
    print(out, len(text), "chars")


if __name__ == "__main__":
    main()
